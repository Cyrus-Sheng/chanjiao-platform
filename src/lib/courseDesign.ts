function allocateHours(total: number, count: number) {
  const base = Math.floor(Math.abs(total) / count);
  const remainder = Math.abs(total) - base * count;
  return Array.from({ length: count }, (_, index) => base + (index < remainder ? 1 : 0));
}

export function courseDesign(action: ActionItem, profile: ProgramProfile) {
  const rule = rules.find(item => item.match.test(`${action.name} ${action.covers.join(' ')}`));
  const modules = rule?.modules ?? [
    ['领域概念与政策框架', `建立${action.covers[0] ?? action.name}的核心概念、产业场景与政策边界。`],
    ['核心方法与工作流程', `拆解${action.covers[0] ?? action.name}的关键方法、工具与标准工作流程。`],
    ['数据分析与案例研判', '通过真实案例完成数据证据、问题诊断和方案比较。'],
    ['综合项目与成果答辩', '形成可展示、可复核的项目成果并进行口头答辩。'],
  ];
  const hours = allocateHours(action.hours, modules.length);
  const assessment = rule?.assessment ?? [['过程作业', 30, '概念与流程作业'], ['案例实验', 30, '案例或数据实验'], ['综合项目', 40, '项目报告与答辩']];
  const prerequisites = (rule?.prerequisites ?? [{ suggestion: '数学/统计或相关领域基础', match: /数学|统计|数据|计算/ }, { suggestion: '编程或专业导论基础', match: /编程|Python|导论|基础/ }]).map(item => {
    const matched = profile.courses.find(course => item.match.test(String(course['课名'])) && String(course['课名']) !== action.name);
    return { suggestion: item.suggestion, available: Boolean(matched), existingCourse: matched ? String(matched['课名']) : null, semester: matched ? String(matched['开课学期']) : null, note: matched ? '当前课程池已有课程可承接' : '当前课程池未检出，建议跨院补修或设置先修学习包' };
  });
  return {
    modules: modules.map(([name, content], index) => ({ name, content, hours: hours[index], outcome: `完成“${name}”学习成果与可检查作业` })),
    assessment: assessment.map(([name, weight, evidence]) => ({ name, weight, evidence })),
    prerequisites,
  };
}
